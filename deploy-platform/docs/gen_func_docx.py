def _font(run, name="宋体", size=11, bold=False, color=None):
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = name
    rpr = run._element.get_or_add_rPr()
    rpr.get_or_add_rFonts().set(qn("w:eastAsia"), name)
    if color:
        run.font.color.rgb = color


def H(doc, text, level):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        _font(run, "黑体", {1: 16, 2: 13, 3: 12}.get(level, 11), True)
    return p


def P(doc, text):
    p = doc.add_paragraph()
    _font(p.add_run(text))
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing = 1.2
    return p


def bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        _font(p.add_run(it))
        p.paragraph_format.space_after = Pt(2)


def module(doc, title, what, funcs, highlights):
    H(doc, title, 1)
    H(doc, "这个模块做什么", 2)
    P(doc, what)
    H(doc, "功能", 2)
    bullets(doc, funcs)
    H(doc, "核心亮点", 2)
    bullets(doc, highlights)


